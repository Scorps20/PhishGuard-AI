"""Stage 3: evaluate the trained model and save the results.

Usage:
    python evaluate_model.py

Reports metrics for the train, validation and test splits, each one
overall and separately for email and SMS. Only the TEST numbers should be
quoted as the model's performance: the train set was used for fitting
and the validation set was used for choosing thresholds.

Writes:
    reports/evaluation.json           - all numbers, machine-readable
    reports/evaluation_summary.md     - readable summary
    reports/confusion_matrix_test.png - test-set confusion matrices
"""

import json
import sys

import joblib
import matplotlib

matplotlib.use("Agg")  # draw to a file, no window needed
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import (
    ConfusionMatrixDisplay,
    accuracy_score,
    brier_score_loss,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)

from src.config import (
    CONFUSION_MATRIX_PATH,
    EVALUATION_REPORT_PATH,
    EVALUATION_SUMMARY_PATH,
    LABEL_PHISHING,
    MODEL_PATH,
    REPORTS_DIR,
    TEST_SET_PATH,
    THRESHOLDS_PATH,
    TRAIN_SET_PATH,
    VALIDATION_SET_PATH,
    load_json,
)

SPLITS = {"train": TRAIN_SET_PATH, "validation": VALIDATION_SET_PATH, "test": TEST_SET_PATH}
GROUPS = ["overall", "email", "sms"]
CLASS_NAMES = ["legitimate", "phishing"]


def compute_metrics(y_true, y_pred) -> dict:
    """Standard metrics, with 'phishing' as the positive class."""
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "messages": int(len(y_true)),
        "phishing_messages": int(np.sum(y_true)),
        "accuracy": round(accuracy_score(y_true, y_pred), 4),
        "precision": round(precision_score(y_true, y_pred, zero_division=0), 4),
        "recall": round(recall_score(y_true, y_pred, zero_division=0), 4),
        "f1": round(f1_score(y_true, y_pred, zero_division=0), 4),
        "confusion_matrix": {
            "true_negatives": int(tn), "false_positives": int(fp),
            "false_negatives": int(fn), "true_positives": int(tp),
        },
        "classification_report": classification_report(
            y_true, y_pred, labels=[0, 1], target_names=CLASS_NAMES,
            output_dict=True, zero_division=0,
        ),
    }


def calibration_check(y_true, scores, bins: int = 5) -> dict:
    """Compare the model's score with how often messages were really phishing.

    If the score were a well-calibrated probability, messages scoring ~0.8
    would be phishing ~80% of the time. This table lets us check that.
    """
    edges = np.linspace(0, 1, bins + 1)
    rows = []
    for low, high in zip(edges[:-1], edges[1:]):
        in_bin = (scores >= low) & ((scores < high) | (high == 1.0))
        if in_bin.sum() == 0:
            continue
        rows.append({
            "score_range": f"{low:.1f}-{high:.1f}",
            "messages": int(in_bin.sum()),
            "average_score": round(float(scores[in_bin].mean()), 3),
            "actual_phishing_rate": round(float(y_true[in_bin].mean()), 3),
        })
    return {"brier_score": round(brier_score_loss(y_true, scores), 4), "bins": rows}


def top_terms(pipeline, count: int = 20) -> dict:
    """The words/phrases with the strongest weights. Useful for spotting dataset bias."""
    vocabulary = pipeline.named_steps["tfidf"].get_feature_names_out()
    weights = pipeline.named_steps["classifier"].coef_[0]
    order = np.argsort(weights)
    return {
        "towards_phishing": [str(vocabulary[i]) for i in order[::-1][:count]],
        "towards_legitimate": [str(vocabulary[i]) for i in order[:count]],
    }


def save_confusion_matrices(test_results: dict, path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.2))
    for axis, group in zip(axes, GROUPS):
        cm = test_results[group]["confusion_matrix"]
        matrix = np.array([[cm["true_negatives"], cm["false_positives"]],
                           [cm["false_negatives"], cm["true_positives"]]])
        ConfusionMatrixDisplay(matrix, display_labels=CLASS_NAMES).plot(
            ax=axis, cmap="Blues", colorbar=False, values_format="d")
        axis.set_title(f"Test set: {group}")
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def write_summary(results: dict, path) -> None:
    lines = [
        "# PhishGuard AI: evaluation summary",
        "",
        f"Generated by `evaluate_model.py`. Classification threshold: "
        f"{results['thresholds']['classification_threshold']}. Positive class: phishing.",
        "",
        "Only the **test** rows describe expected performance on unseen data from these "
        "datasets. Train rows are optimistic (the model learned from them); validation rows "
        "were used to pick risk thresholds. None of these numbers prove real-world accuracy.",
        "",
        "| Split | Group | Messages | Phishing | Accuracy | Precision | Recall | F1 | FP | FN |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for split, groups in results["splits"].items():
        for group, m in groups.items():
            cm = m["confusion_matrix"]
            lines.append(
                f"| {split} | {group} | {m['messages']} | {m['phishing_messages']} | "
                f"{m['accuracy']:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | "
                f"{cm['false_positives']} | {cm['false_negatives']} |"
            )
    cal = results["validation_calibration_check"]
    lines += ["", "## Is the score a probability? (validation set)", "",
              f"Brier score: {cal['brier_score']} (lower is better).", "",
              "| Score range | Messages | Average score | Actual phishing rate |", "|---|---|---|---|"]
    lines += [f"| {r['score_range']} | {r['messages']} | {r['average_score']} | {r['actual_phishing_rate']} |"
              for r in cal["bins"]]
    terms = results["top_terms"]
    lines += ["", "## Strongest terms", "",
              "Towards phishing: " + ", ".join(f"`{t}`" for t in terms["towards_phishing"]), "",
              "Towards legitimate: " + ", ".join(f"`{t}`" for t in terms["towards_legitimate"]), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    missing = [p for p in [MODEL_PATH, THRESHOLDS_PATH, *SPLITS.values()] if not p.exists()]
    if missing:
        print("ERROR: missing files:", *[f"  - {p}" for p in missing], sep="\n")
        print("Run first:  python train_model.py")
        return 1

    pipeline = joblib.load(MODEL_PATH)
    thresholds = load_json(THRESHOLDS_PATH)
    cutoff = thresholds["classification_threshold"]

    results = {"thresholds": thresholds, "splits": {}}
    for split_name, split_path in SPLITS.items():
        df = pd.read_csv(split_path)
        scores = pipeline.predict_proba(df["text"])[:, 1]
        y_true = (df["label"] == LABEL_PHISHING).astype(int).to_numpy()
        y_pred = (scores >= cutoff).astype(int)
        results["splits"][split_name] = {}
        for group in GROUPS:
            mask = np.ones(len(df), bool) if group == "overall" else (df["channel"] == group).to_numpy()
            results["splits"][split_name][group] = compute_metrics(y_true[mask], y_pred[mask])
        if split_name == "validation":
            results["validation_calibration_check"] = calibration_check(y_true, scores)

    results["top_terms"] = top_terms(pipeline)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    with open(EVALUATION_REPORT_PATH, "w", encoding="utf-8") as file:
        json.dump(results, file, indent=2)
    write_summary(results, EVALUATION_SUMMARY_PATH)
    save_confusion_matrices(results["splits"]["test"], CONFUSION_MATRIX_PATH)

    print(f"{'split':<11}{'group':<9}{'n':>6}{'acc':>8}{'prec':>8}{'recall':>8}{'f1':>8}{'FP':>5}{'FN':>5}")
    for split, groups in results["splits"].items():
        for group, m in groups.items():
            cm = m["confusion_matrix"]
            print(f"{split:<11}{group:<9}{m['messages']:>6}{m['accuracy']:>8.3f}{m['precision']:>8.3f}"
                  f"{m['recall']:>8.3f}{m['f1']:>8.3f}{cm['false_positives']:>5}{cm['false_negatives']:>5}")
    print("\nTest-set classification report (overall):")
    test_df = pd.read_csv(TEST_SET_PATH)
    test_pred = (pipeline.predict_proba(test_df["text"])[:, 1] >= cutoff).astype(int)
    print(classification_report((test_df["label"] == LABEL_PHISHING).astype(int), test_pred,
                                target_names=CLASS_NAMES, digits=3))
    print(f"Saved: {EVALUATION_REPORT_PATH}\n       {EVALUATION_SUMMARY_PATH}\n       {CONFUSION_MATRIX_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
